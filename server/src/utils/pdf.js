import PDFDocument from 'pdfkit';

// Builds a simple, readable A4 PDF from blocks:
// { heading }, { text }, { fields: [[label, value], ...] }, { list: [...] }, { divider: true }
export function buildPdf({ title, subtitle, blocks = [] }) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margin: 56, info: { Title: title, Author: 'BarrierFix' } });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    doc.font('Helvetica-Bold').fontSize(18).fillColor('#1d2a3a').text(title);
    if (subtitle) doc.moveDown(0.3).font('Helvetica').fontSize(10).fillColor('#5b6676').text(subtitle);
    doc.moveDown(1);

    for (const block of blocks) {
      if (block.heading) {
        doc.moveDown(0.6).font('Helvetica-Bold').fontSize(13).fillColor('#1d2a3a').text(block.heading);
        doc.moveDown(0.3);
      }
      if (block.text) doc.font('Helvetica').fontSize(11).fillColor('#222').text(block.text, { lineGap: 2 }).moveDown(0.4);
      if (block.fields) {
        for (const [label, value] of block.fields) {
          doc.font('Helvetica-Bold').fontSize(11).fillColor('#222').text(`${label}: `, { continued: true });
          doc.font('Helvetica').text(value === undefined || value === null || value === '' ? 'Not recorded' : String(value), { lineGap: 2 });
        }
        doc.moveDown(0.4);
      }
      if (block.list) {
        block.list.forEach((item, i) => doc.font('Helvetica').fontSize(11).fillColor('#222').text(`${i + 1}. ${item}`, { indent: 10, lineGap: 2 }));
        doc.moveDown(0.4);
      }
      if (block.divider) {
        doc.moveDown(0.3).strokeColor('#d0d5dc').moveTo(56, doc.y).lineTo(539, doc.y).stroke().moveDown(0.6);
      }
    }

    doc.moveDown(1.5).font('Helvetica').fontSize(8).fillColor('#5b6676')
      .text(`Generated by BarrierFix on ${new Date().toUTCString()}. BarrierFix records decisions; it does not give legal advice.`);
    doc.end();
  });
}
